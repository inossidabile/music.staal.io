#!/usr/bin/env python3
"""Generates the forwarding pages for music.staal.io from links.tsv.

GitHub Pages cannot send HTTP redirects, so each link is a tiny HTML page
that forwards the browser to its target:

  music.staal.io/<path>  ->  <path>/index.html  ->  target URL
  music.staal.io         ->  index.html         ->  ROOT_TARGET
  unknown path           ->  404.html (lists every link)

Usage: edit links.tsv, run `python3 build.py`, commit and push.
"""

import html
import json
import pathlib
import re
import shutil

SITE = "https://music.staal.io"
ARTIST = "Boris Staal"
# Where music.staal.io itself forwards to. Set to a path from links.tsv.
ROOT_PATH = "soundcloud"

HERE = pathlib.Path(__file__).resolve().parent
MARKER = "<!-- generated by build.py -->"

STUB = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
{marker}
<title>{title}</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="{target}">
<meta property="og:title" content="{title}">
<meta property="og:url" content="{target}">
<meta property="og:image" content="{site}/avatar.jpg">
<meta http-equiv="refresh" content="0; url={target}">
<script>location.replace({target_js});</script>
</head>
<body>
<p>Redirecting to <a href="{target}">{title}</a>&hellip;</p>
</body>
</html>
"""

NOT_FOUND = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
{marker}
<title>{artist}</title>
<meta name="robots" content="noindex">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
body {{ background: #0e0e0e; color: #ddd; font: 16px/1.6 system-ui, sans-serif;
       max-width: 28rem; margin: 4rem auto; padding: 0 1rem; }}
a {{ color: #f5b300; }}
li {{ list-style: none; }} ul {{ padding: 0; }}
</style>
</head>
<body>
<h1>{artist}</h1>
<p>That link doesn't exist. These do:</p>
<ul>
{items}
</ul>
</body>
</html>
"""


def read_links():
    links = []
    for number, line in enumerate(
        (HERE / "links.tsv").read_text(encoding="utf-8").splitlines(), 1
    ):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit(f"links.tsv line {number}: expected 3 tab-separated fields")
        path, label, target = (p.strip() for p in parts)
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", path):
            raise SystemExit(f"links.tsv line {number}: bad path {path!r}")
        if not target.startswith("https://"):
            raise SystemExit(f"links.tsv line {number}: target must start with https://")
        if any(path == existing[0] for existing in links):
            raise SystemExit(f"links.tsv line {number}: duplicate path {path!r}")
        links.append((path, label, target))
    return links


def stub(label, target):
    return STUB.format(
        marker=MARKER,
        title=html.escape(f"{ARTIST} on {label}"),
        target=html.escape(target, quote=True),
        target_js=json.dumps(target).replace("</", "<\\/"),
        site=SITE,
    )


def main():
    links = read_links()
    by_path = {path: (label, target) for path, label, target in links}
    if ROOT_PATH not in by_path:
        raise SystemExit(f"ROOT_PATH {ROOT_PATH!r} is not in links.tsv")

    # Remove pages generated earlier for links that no longer exist.
    for index in HERE.glob("*/index.html"):
        if MARKER in index.read_text(encoding="utf-8") and index.parent.name not in by_path:
            shutil.rmtree(index.parent)

    for path, label, target in links:
        (HERE / path).mkdir(exist_ok=True)
        (HERE / path / "index.html").write_text(stub(label, target), encoding="utf-8")

    (HERE / "index.html").write_text(stub(*by_path[ROOT_PATH]), encoding="utf-8")

    items = "\n".join(
        f'<li><a href="/{path}">{html.escape(label)}</a></li>' for path, label, _ in links
    )
    (HERE / "404.html").write_text(
        NOT_FOUND.format(marker=MARKER, artist=html.escape(ARTIST), items=items),
        encoding="utf-8",
    )

    (HERE / "CNAME").write_text("music.staal.io\n", encoding="utf-8")
    (HERE / ".nojekyll").write_text("", encoding="utf-8")
    print(f"Built {len(links)} links, index.html -> /{ROOT_PATH}, 404.html, CNAME")


if __name__ == "__main__":
    main()
