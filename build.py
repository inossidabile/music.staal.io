#!/usr/bin/env python3
"""Generates the forwarding pages for music.staal.io from links.tsv.

GitHub Pages cannot send HTTP redirects, so each link is a tiny HTML page
that forwards the browser to its target:

  music.staal.io/<path>  ->  <path>/index.html  ->  target URL
  music.staal.io         ->  index.html         ->  ROOT_TARGET
  unknown path           ->  404.html (lists every link)

Usage: edit links.tsv, run `python3 build.py`, commit and push.
"""

import html
import json
import pathlib
import re
import shutil

SITE = "https://music.staal.io"
ARTIST = "Boris Staal"
BIO = (
    "Home of Vsratosphere. Random stuff put to rhythm and glitch that talks back "
    "and won\u2019t behave. Lorem ipsum dolor sit amet. Stop reading this lol. \U0001F9A6"
)
# What music.staal.io itself does: a path from links.tsv forwards there;
# None shows a page listing every link.
ROOT_PATH = None
# Paths that still forward but are left off the links page and the 404 page.
HIDDEN = {"instagram"}

HERE = pathlib.Path(__file__).resolve().parent
MARKER = "<!-- generated by build.py -->"

STUB = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
{marker}
<title>{title}</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="{target}">
<meta property="og:title" content="{title}">
<meta property="og:url" content="{target}">
<meta property="og:image" content="{site}/avatar.jpg">
<meta http-equiv="refresh" content="0; url={target}">
<script>location.replace({target_js});</script>
</head>
<body>
<p>Redirecting to <a href="{target}">{title}</a>&hellip;</p>
</body>
</html>
"""

NOT_FOUND = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
{marker}
<title>{artist}</title>
<meta name="robots" content="noindex">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
body {{ background: #0e0e0e; color: #ddd; font: 16px/1.6 system-ui, sans-serif;
       max-width: 28rem; margin: 4rem auto; padding: 0 1rem; }}
a {{ color: #f5b300; }}
li {{ list-style: none; }} ul {{ padding: 0; }}
</style>
</head>
<body>
<h1>{artist}</h1>
<p>That link doesn't exist. These do:</p>
<ul>
{items}
</ul>
</body>
</html>
"""


LINKS_PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
{marker}
<title>{artist}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{bio}">
<link rel="canonical" href="{site}/">
<meta property="og:title" content="{artist}">
<meta property="og:description" content="{bio}">
<meta property="og:url" content="{site}/">
<meta property="og:image" content="{site}/avatar.jpg">
<link rel="icon" href="/avatar.jpg">
<style>
* {{ box-sizing: border-box; }}
body {{ margin: 0; background: #0e0e0e; color: #e6e6e6;
       font: 16px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }}
main {{ max-width: 26rem; margin: 0 auto; padding: 3rem 1.25rem 4rem; text-align: center; }}
img {{ width: 8rem; height: 8rem; border-radius: 50%; display: block; margin: 0 auto 1.25rem; }}
h1 {{ font-size: 1.6rem; margin: 0 0 .5rem; letter-spacing: .02em; }}
p {{ margin: 0 0 2rem; color: #a8a8a8; }}
ul {{ list-style: none; margin: 0; padding: 0; }}
li {{ margin: 0 0 .75rem; }}
a {{ display: block; padding: .85rem 1rem; border: 1px solid #333; border-radius: .6rem;
     background: #171717; color: #e6e6e6; text-decoration: none; font-weight: 600; }}
a:hover, a:focus {{ border-color: #f5b300; color: #f5b300; outline: none; }}
</style>
</head>
<body>
<main>
<img src="/avatar.jpg" alt="{artist}" width="128" height="128">
<h1>{artist}</h1>
<p>{bio}</p>
<ul>
{items}
</ul>
</main>
</body>
</html>
"""


def links_page(links):
    items = "\n".join(
        f'<li><a href="/{path}">{html.escape(label)}</a></li>' for path, label, _ in links
    )
    return LINKS_PAGE.format(
        marker=MARKER,
        artist=html.escape(ARTIST),
        bio=html.escape(BIO, quote=True),
        site=SITE,
        items=items,
    )


def read_links():
    links = []
    for number, line in enumerate(
        (HERE / "links.tsv").read_text(encoding="utf-8").splitlines(), 1
    ):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit(f"links.tsv line {number}: expected 3 tab-separated fields")
        path, label, target = (p.strip() for p in parts)
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", path):
            raise SystemExit(f"links.tsv line {number}: bad path {path!r}")
        if not target.startswith("https://"):
            raise SystemExit(f"links.tsv line {number}: target must start with https://")
        if any(path == existing[0] for existing in links):
            raise SystemExit(f"links.tsv line {number}: duplicate path {path!r}")
        links.append((path, label, target))
    return links


def stub(label, target):
    return STUB.format(
        marker=MARKER,
        title=html.escape(f"{ARTIST} on {label}"),
        target=html.escape(target, quote=True),
        target_js=json.dumps(target).replace("</", "<\\/"),
        site=SITE,
    )


def main():
    links = read_links()
    by_path = {path: (label, target) for path, label, target in links}
    if ROOT_PATH is not None and ROOT_PATH not in by_path:
        raise SystemExit(f"ROOT_PATH {ROOT_PATH!r} is not in links.tsv")

    # Remove pages generated earlier for links that no longer exist.
    for index in HERE.glob("*/index.html"):
        if MARKER in index.read_text(encoding="utf-8") and index.parent.name not in by_path:
            shutil.rmtree(index.parent)

    for path, label, target in links:
        (HERE / path).mkdir(exist_ok=True)
        (HERE / path / "index.html").write_text(stub(label, target), encoding="utf-8")

    listed = [link for link in links if link[0] not in HIDDEN]
    root = links_page(listed) if ROOT_PATH is None else stub(*by_path[ROOT_PATH])
    (HERE / "index.html").write_text(root, encoding="utf-8")

    items = "\n".join(
        f'<li><a href="/{path}">{html.escape(label)}</a></li>' for path, label, _ in listed
    )
    (HERE / "404.html").write_text(
        NOT_FOUND.format(marker=MARKER, artist=html.escape(ARTIST), items=items),
        encoding="utf-8",
    )

    (HERE / "CNAME").write_text("music.staal.io\n", encoding="utf-8")
    (HERE / ".nojekyll").write_text("", encoding="utf-8")
    root_desc = "links page" if ROOT_PATH is None else f"/{ROOT_PATH}"
    print(f"Built {len(links)} links, index.html -> {root_desc}, 404.html, CNAME")


if __name__ == "__main__":
    main()
